namespace CosmicSandbox.Core.Constants;

/// <summary>
/// Physical constants for gravitational simulations
/// </summary>
public static class PhysicsConstants
{
    /// <summary>
    /// Gravitational constant (m³ kg⁻¹ s⁻²)
    /// </summary>
    public const double G = 6.67430e-11;

    /// <summary>
    /// Speed of light (m/s)
    /// </summary>
    public const double C = 299792458.0;

    /// <summary>
    /// Astronomical Unit (meters)
    /// </summary>
    public const double AU = 1.495978707e11;

    /// <summary>
    /// Solar mass (kg)
    /// </summary>
    public const double SolarMass = 1.98892e30;

    /// <summary>
    /// Earth mass (kg)
    /// </summary>
    public const double EarthMass = 5.97237e24;

    /// <summary>
    /// Earth radius (meters)
    /// </summary>
    public const double EarthRadius = 6.371e6;

    /// <summary>
    /// Solar radius (meters)
    /// </summary>
    public const double SolarRadius = 6.96e8;

    /// <summary>
    /// Seconds per day
    /// </summary>
    public const double SecondsPerDay = 86400.0;

    /// <summary>
    /// Days per year (Julian)
    /// </summary>
    public const double DaysPerYear = 365.25;

    /// <summary>
    /// Parsec (meters)
    /// </summary>
    public const double Parsec = 3.0857e16;

    /// <summary>
    /// Light year (meters)
    /// </summary>
    public const double LightYear = 9.4607e15;
}
